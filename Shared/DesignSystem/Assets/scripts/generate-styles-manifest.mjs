/**
 * generate-styles-manifest.mjs — Socratic Master Stylesheet Generator
 *
 * Dynamically discovers ALL modular CSS files across wwwroot/css/ recursively
 * and automatically generates wwwroot/css/styles.css mapped to architectural
 * Cascade Layers (@layer):
 *   0. fonts/        → Unlayered @import
 *   1. tokens/       → @layer tokens
 *   2. foundations/  → @layer foundations (reset.css first, then alphabetical)
 *   3. components/   → @layer components
 *   4. widgets/      → @layer widgets
 *   5. pages/        → @layer pages
 *   6. layouts/      → @layer layouts
 *
 * Zero hardcoded file lists. Any new file added to any directory or nested subfolder
 * is automatically discovered and registered on MSBuild compilation or `npm run generate:styles`.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const cssRoot = path.resolve(__dirname, '../wwwroot/css');
const stylesManifestPath = path.join(cssRoot, 'styles.css');

/**
 * Recursively find all .css files under a given directory.
 */
function findCssFiles(dir) {
  const results = [];
  if (!fs.existsSync(dir)) return results;

  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...findCssFiles(fullPath));
    } else if (
      entry.isFile() &&
      entry.name.endsWith('.css') &&
      !entry.name.endsWith('.min.css') &&
      entry.name !== 'styles.css'
    ) {
      results.push(fullPath);
    }
  }
  return results;
}

/**
 * Natural sort with reset.css given precedence in foundations.
 */
function sortLayerFiles(files, isFoundations = false) {
  return [...files].sort((a, b) => {
    if (isFoundations) {
      const aIsReset = path.basename(a) === 'reset.css';
      const bIsReset = path.basename(b) === 'reset.css';
      if (aIsReset && !bIsReset) return -1;
      if (!aIsReset && bIsReset) return 1;
    }
    return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
  });
}

function generateStylesManifest() {
  console.log(`\n🔍 [generate-styles-manifest] Scanning ${cssRoot} for CSS files...`);

  const allFiles = findCssFiles(cssRoot);

  // Group files dynamically by top-level category
  const layers = {
    fonts: [],
    tokens: [],
    foundations: [],
    components: [],
    widgets: [],
    pages: [],
    layouts: [],
    other: []
  };

  for (const fullPath of allFiles) {
    const relPath = path.relative(cssRoot, fullPath).replace(/\\/g, '/');
    const topFolder = relPath.split('/')[0].toLowerCase();

    if (layers[topFolder]) {
      layers[topFolder].push(relPath);
    } else {
      layers.other.push(relPath);
    }
  }

  // Sort files within each layer dynamically without hardcoded lists
  const fonts = sortLayerFiles(layers.fonts);
  const tokens = sortLayerFiles(layers.tokens);
  const foundations = sortLayerFiles(layers.foundations, true);
  const components = sortLayerFiles(layers.components);
  const widgets = sortLayerFiles(layers.widgets);
  const pages = sortLayerFiles(layers.pages);
  const layouts = sortLayerFiles(layers.layouts);
  const other = sortLayerFiles(layers.other);

  const totalImports =
    fonts.length +
    tokens.length +
    foundations.length +
    components.length +
    widgets.length +
    pages.length +
    layouts.length +
    other.length;

  let output = `/* ==========================================================================
   Socratic Platform - Master Design System Stylesheet
   AUTO-GENERATED BY scripts/generate-styles-manifest.mjs. DO NOT EDIT MANUALLY.
   Cascade Layers (@layer)
   ========================================================================== */

/* Layer Precedence (Lower to Higher Priority: tokens -> foundations -> components -> widgets -> pages -> layouts) */
@layer tokens, foundations, components, widgets, pages, layouts;
`;

  // 0. Fonts
  if (fonts.length > 0) {
    output += `\n/* 0. Typography Fonts */\n`;
    for (const f of fonts) {
      output += `@import "${f}";\n`;
    }
  }

  // 1. Tokens
  if (tokens.length > 0) {
    output += `\n/* 1. Design Tokens (W3C DTCG Standard Types) */\n`;
    for (const f of tokens) {
      output += `@import "${f}" layer(tokens);\n`;
    }
  }

  // 2. Foundations
  if (foundations.length > 0) {
    output += `\n/* 2. Foundations & Reset */\n`;
    for (const f of foundations) {
      output += `@import "${f}" layer(foundations);\n`;
    }
  }

  // 3. Components
  if (components.length > 0) {
    output += `\n/* 3. Material 3 Component Primitives (Protected UI Units) */\n`;
    for (const f of components) {
      output += `@import "${f}" layer(components);\n`;
    }
  }

  // 4. Widgets
  if (widgets.length > 0) {
    output += `\n/* 4. Smart Widgets & Composite Tools (Domain Organisms) */\n`;
    for (const f of widgets) {
      output += `@import "${f}" layer(widgets);\n`;
    }
  }

  // 5. Pages
  if (pages.length > 0) {
    output += `\n/* 5. Page-Specific Styles (Macro Screen Contexts) */\n`;
    for (const f of pages) {
      output += `@import "${f}" layer(pages);\n`;
    }
  }

  // 6. Layouts
  if (layouts.length > 0) {
    output += `\n/* 6. Blazor Layouts (Page Skeletons, Shells & Chrome) */\n`;
    for (const f of layouts) {
      output += `@import "${f}" layer(layouts);\n`;
    }
  }

  // 7. Other / Uncategorized (if any)
  if (other.length > 0) {
    output += `\n/* 7. Additional Modules */\n`;
    for (const f of other) {
      output += `@import "${f}";\n`;
    }
  }

  // Check if unchanged to preserve timestamp
  if (fs.existsSync(stylesManifestPath)) {
    const existing = fs.readFileSync(stylesManifestPath, 'utf8');
    if (existing === output) {
      console.log(`✅ [generate-styles-manifest] styles.css is up to date (${totalImports} discovered stylesheets).`);
      return;
    }
  }

  fs.writeFileSync(stylesManifestPath, output, 'utf8');
  console.log(`✨ [generate-styles-manifest] Generated styles.css (${totalImports} discovered stylesheets across 6 layers).`);
}

generateStylesManifest();
