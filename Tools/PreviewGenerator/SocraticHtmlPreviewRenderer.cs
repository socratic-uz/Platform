using System.Diagnostics.CodeAnalysis;
using System.Globalization;
using System.Reflection;
using System.Text.RegularExpressions;
using Microsoft.AspNetCore.Components;
using Microsoft.AspNetCore.Components.Web;
using Microsoft.Extensions.Logging.Abstractions;

namespace Socratic.PreviewGenerator;

public sealed partial class SocraticHtmlPreviewRenderer
{
    private readonly IServiceProvider _services;

    public SocraticHtmlPreviewRenderer(IServiceProvider services)
    {
        _services = services;
    }

    public async Task<string> RenderComponentAsync<[DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.All)] TComponent>(IDictionary<string, object?>? parameters = null) 
        where TComponent : IComponent
    {
        await using var htmlRenderer = new HtmlRenderer(_services, NullLoggerFactory.Instance);

        var layoutAttr = typeof(TComponent).GetCustomAttribute<LayoutAttribute>(inherit: true);
        var layoutType = layoutAttr?.LayoutType;

        var wrapperParameters = new Dictionary<string, object?>
        {
            [nameof(LayoutWrapper<TComponent>.LayoutType)] = layoutType,
            [nameof(LayoutWrapper<TComponent>.ComponentParameters)] = parameters
        };

        var paramView = ParameterView.FromDictionary(wrapperParameters);

        var (headFragment, bodyFragment) = await htmlRenderer.Dispatcher.InvokeAsync(async () =>
        {
            var headParams = ParameterView.FromDictionary(new Dictionary<string, object?>
            {
                [nameof(Shared.Components.HeadAssets.BasePath)] = "../",
                [nameof(Shared.Components.HeadAssets.IncludeBase)] = false,
                [nameof(Shared.Components.HeadAssets.IncludeMarketingAndAds)] = false,
                [nameof(Shared.Components.HeadAssets.IncludeTelegram)] = false
            });
            var headOutput = await htmlRenderer.RenderComponentAsync<Shared.Components.HeadAssets>(headParams);

            var bodyOutput = await htmlRenderer.RenderComponentAsync<LayoutWrapper<TComponent>>(paramView);

            return (headOutput.ToHtmlString(), bodyOutput.ToHtmlString());
        });

        var envelopeHtml = WrapInHtmlEnvelope(typeof(TComponent).Name, headFragment, bodyFragment);
        return CleanHtmlEntities(envelopeHtml);
    }

    [GeneratedRegex(@"&#x([0-9a-fA-F]+);")]
    private static partial Regex HexEntityRegex();

    [GeneratedRegex(@"&#([0-9]+);")]
    private static partial Regex DecEntityRegex();

    public static string CleanHtmlEntities(string html)
    {
        // Decode hex entities (e.g. &#x27; -> ', &#x41F; -> П) while preserving < > & "
        html = HexEntityRegex().Replace(html, m =>
        {
            if (int.TryParse(m.Groups[1].ValueSpan, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out int codePoint))
            {
                if (codePoint is 0x3C or 0x3E or 0x26 or 0x22)
                {
                    return m.Value;
                }
                return char.ConvertFromUtf32(codePoint);
            }
            return m.Value;
        });

        // Decode decimal entities (e.g. &#39; -> ') while preserving < > & "
        html = DecEntityRegex().Replace(html, m =>
        {
            if (int.TryParse(m.Groups[1].ValueSpan, NumberStyles.Integer, CultureInfo.InvariantCulture, out int codePoint))
            {
                if (codePoint is 0x3C or 0x3E or 0x26 or 0x22)
                {
                    return m.Value;
                }
                return char.ConvertFromUtf32(codePoint);
            }
            return m.Value;
        });

        // Rewrite RCL static web asset prefix (_content/Assets/) to relative ../ path for standalone preview HTML
        html = html.Replace("\"_content/Assets/", "\"../", StringComparison.Ordinal)
                   .Replace("'_content/Assets/", "'../", StringComparison.Ordinal);

        return html;
    }

    public static string WrapInHtmlEnvelope(string pageTitle, string headHtml, string contentHtml) =>
        $"""
        <!DOCTYPE html>
        <html lang="ru" data-theme="dark">
        <head>
            <title>Socratic Preview • {pageTitle}</title>
            {headHtml}
        </head>
        <body class="{Assets.Constants.Classes.GridLayout.AppGrid} m3-surface">
            <!-- AUTO-GENERATED BY SOCRATIC HTML RENDERER. DO NOT EDIT MANUALLY. -->
            {contentHtml}
        </body>
        </html>
        """;
}

[DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.All)]
internal sealed class LayoutWrapper<[DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.All)] TComponent> : ComponentBase
    where TComponent : IComponent
{
    [Parameter] public Type? LayoutType { get; set; }
    [Parameter] public IDictionary<string, object?>? ComponentParameters { get; set; }

    protected override void BuildRenderTree(Microsoft.AspNetCore.Components.Rendering.RenderTreeBuilder builder)
    {
        if (LayoutType != null)
        {
            builder.OpenComponent<LayoutView>(0);
            builder.AddAttribute(1, nameof(LayoutView.Layout), LayoutType);
            builder.AddAttribute(2, nameof(LayoutView.ChildContent), (RenderFragment)RenderChild);
            builder.CloseComponent();
        }
        else
        {
            RenderChild(builder);
        }
    }

    private void RenderChild(Microsoft.AspNetCore.Components.Rendering.RenderTreeBuilder builder)
    {
        builder.OpenComponent<TComponent>(0);
        if (ComponentParameters != null)
        {
            int seq = 1;
            foreach (var (k, v) in ComponentParameters)
            {
                builder.AddAttribute(seq++, k, v);
            }
        }
        builder.CloseComponent();
    }
}
